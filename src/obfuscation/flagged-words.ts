const hash = (value: string) =>
	createHash('sha256').update(value).digest('hex').slice(0, 12);

export function isFlaggedWord(word: string) {
	const lower = word.toLowerCase();
	if (flaggedWords.has(hash(lower))) return true;
	for (let start = 0; start < lower.length; start++)
		for (let end = start + 3; end <= lower.length; end++)
			if (flaggedParts.has(hash(lower.slice(start, end)))) return true;
	return false;
}

export function withoutFlaggedWords(
	keys: Iterable<string>,
	generate: (keys: string[]) => Record<string, string>
) {
	const wanted = [...new Set(keys)];
	const spares = wanted.map((_, index) => `\0spare${index}`);
	const names = generate([...wanted, ...spares]);
	const clean = spares
		.map((spare) => names[spare])
		.filter((name): name is string => !!name && !isFlaggedWord(name));
	return Object.fromEntries(
		wanted.map((key) => {
			const name = names[key];
			if (name && !isFlaggedWord(name)) return [key, name];
			const replacement = clean.pop();
			if (!replacement)
				throw new Error('Merp generated too many flagged path names');
			return [key, replacement];
		})
	);
}
