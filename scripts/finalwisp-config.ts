// scripts/finalwisp-config.ts: writes the config shared by the pm2 finalwisp
// instances (finalwisp.config.cjs) from config.json, so the policy, limits and
// dns setting follow the site. Run it (then `pm2 restart finalwisp.config.cjs`)
// after changing config.json:
//
//   node scripts/finalwisp-config.ts [/etc/finalwisp/common.conf]
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname } from 'node:path';
import { resolveDnsServers } from '../src/server/finalwisp.ts';
import {
	finalwispLimits,
	finalwispPolicy,
	wispDns,
} from '../src/server/wisp.ts';

const out = process.argv[2] ?? '/etc/finalwisp/common.conf';

// nginx (scripts/wisp-nginx.ts) sets X-Real-IP, not X-Forwarded-For.
const lines = [
	'# generated by scripts/finalwisp-config.ts from config.json; do not edit',
	'preset public',
	'host 127.0.0.1',
	'trusted-proxy 127.0.0.1',
	'real-ip-header x-real-ip',
	'no-direct-ip',
	`allow-ports ${finalwispPolicy.ports.join(',')}`,
	`max-conns ${finalwispLimits.maxConns}`,
	`max-streams-per-conn ${finalwispLimits.maxStreamsPerConn}`,
	`max-conns-per-ip ${finalwispLimits.maxConnsPerIp}`,
	`conn-rate-per-ip ${finalwispLimits.connRatePerIp}`,
	`stream-rate-per-ip ${finalwispLimits.streamRatePerIp}`,
	`stream-rate-per-dest ${finalwispLimits.streamRatePerDest}`,
	`stream-rate-per-dest-minute ${finalwispLimits.streamRatePerDestMinute}`,
	`log-level ${finalwispLimits.logLevel}`,
];

const { servers, method } = wispDns();
if (servers.length) {
	// --dns-server takes addresses, so names are resolved here; regenerate if
	// the provider's addresses ever change.
	for (const address of await resolveDnsServers(servers))
		lines.push(`dns-server ${address}`);
} else if (method === 'lookup') {
	// The system resolver instead of finalwisp's own (set by the preset).
	lines.push('no-dns-own');
}

mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, `${lines.join('\n')}\n`);
console.log(`wrote ${out} (${lines.length} lines)`);
console.log(
	'Restart the instances to apply it: pm2 restart finalwisp.config.cjs'
);
