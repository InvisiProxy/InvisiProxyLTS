// scripts/wisp-nginx.ts: writes the nginx routes from the generated Wisp path
// names to the finalwisp instances, then tests and reloads nginx. The rebuild
// and refresh scripts run it so the routes follow the path names:
//
//   pnpm run wisp:nginx
//
// FINALWISP_REGIONS limits it to a subset for a gradual move ("" is the
// default region), e.g. FINALWISP_REGIONS=eu. Without nginx on the machine it
// notes that and exits; unrouted regions fall back to the site's managed
// instances while manageWisp is on.
import { spawnSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import {
	finalwispRegionNames,
	finalwispRegions,
	wispPath,
} from '../src/server/wisp.ts';

const out = process.argv[2] ?? '/etc/nginx/snippets/finalwisp-routes.conf';
const routedEnv = process.env.FINALWISP_REGIONS;
const ROUTED = new Set<string>(
	routedEnv === undefined
		? finalwispRegionNames()
		: routedEnv
				.split(',')
				.map((region) => region.trim())
				.filter(Boolean)
);

const base = wispPath(); // e.g. "/abc123/" (ends with "/")
if (!base.startsWith('/') || !base.endsWith('/') || /[\s;{}'"\\]/.test(base))
	throw new Error(`unexpected wisp path: ${JSON.stringify(base)}`);

// The same URLs the site's upgrade handler accepts: BASE for the default,
// BASE + region (with or without a trailing "/") for a region. The
// proxy_pass URI ("/") replaces the matched path.
const lines = ['# generated by scripts/wisp-nginx.ts, do not edit by hand'];
for (const region of finalwispRegionNames()) {
	if (!ROUTED.has(region)) continue;
	const port = finalwispRegions[region]?.port;
	if (!port) throw new Error(`no finalwisp instance for region "${region}"`);
	const paths = region === '' ? [base] : [base + region, `${base + region}/`];
	for (const path of paths)
		lines.push(
			`location = ${path} {`,
			'    include snippets/finalwisp-proxy.conf;',
			`    proxy_pass http://127.0.0.1:${port}/;`,
			'}'
		);
}

const nginx = spawnSync('sh', ['-c', 'command -v nginx'], { encoding: 'utf8' });
if (nginx.status !== 0) {
	console.log(
		'nginx is not installed; skipping the finalwisp routes (the site serves Wisp itself while manageWisp is on).'
	);
	process.exit(0);
}
writeFileSync(out, `${lines.join('\n')}\n`);
console.log(
	`wrote ${out}: ${[...ROUTED].map((r) => r || 'default').join(', ') || 'no regions'}`
);
// pm2's rebuild runs as root; a manual run as another user needs sudo.
const uid = process.getuid?.() ?? -1;
const run = (args: string[]) =>
	spawnSync(
		uid === 0 ? 'nginx' : 'sudo',
		[...(uid === 0 ? [] : ['nginx']), ...args],
		{ stdio: 'inherit' }
	);
run(['-t']);
run(['-s', 'reload']);
console.log('nginx tested and reloaded');
